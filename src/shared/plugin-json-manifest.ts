import { z } from 'zod';
import {
  canonicalPluginLocale,
  createPluginI18n,
  resolvePluginLocalizedMetadata,
  resolvePluginTranslationReferences,
  seedNetworkPermissions,
  type PluginTranslations,
} from '@motus-ai/seed-sdk';
import { seedConsumedCapabilitySchema, seedLocalizedTextSchema, type SeedPluginManifest } from './plugin-manifest';
import { seedVersionPattern } from './seed-version';

const pathSchema = z
  .string()
  .min(1)
  .max(512)
  .refine(
    (value) =>
      !value.includes('\\') &&
      !value.includes('\0') &&
      !value.includes(':') &&
      value
        .split('/')
        .every(
          (part) =>
            part &&
            part !== '.' &&
            part !== '..' &&
            !/[. ]$/.test(part) &&
            !/^(con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\.|$)/i.test(part),
        ),
    'Unsafe resource path.',
  );
const resourceSchema = z.object({ path: pathSchema, sha256: z.string().regex(/^[0-9a-f]{64}$/) }).strict();
const text = (max: number) => z.string().min(1).max(max);
const id = z.string().regex(/^[a-z][a-z0-9-]*(?:\.[a-z0-9-]+)+$/);
const translationReference = z.object({ $t: text(512) }).strict();
const translatedText = (max: number) => z.union([text(max), translationReference]);
const translationDeclaration = z
  .object({
    defaultLocale: text(100),
    resources: z
      .record(z.string().min(1), pathSchema)
      .refine((value) => Object.keys(value).length > 0 && Object.keys(value).length <= 32),
  })
  .strict()
  .superRefine((value, context) => {
    try {
      if (
        canonicalPluginLocale(value.defaultLocale) !== value.defaultLocale ||
        !Object.hasOwn(value.resources, value.defaultLocale)
      )
        throw new Error('Default locale must be declared and canonical.');
      for (const locale of Object.keys(value.resources))
        if (canonicalPluginLocale(locale) !== locale) throw new Error('Locale must use canonical BCP 47 notation.');
    } catch (error) {
      context.addIssue({ code: 'custom', message: String(error) });
    }
  });

/** Built v2 manifest. Loading metadata is generated by the tools, never by plugin execution. */
export const seedPluginJsonManifestSchema = z
  .object({
    id,
    name: translatedText(100),
    version: z.string().regex(seedVersionPattern),
    minAppVersion: z.string().regex(seedVersionPattern),
    description: translatedText(500),
    author: text(100),
    authorUrl: z.string().url().optional(),
    apiVersion: z.literal(2),
    runtime: z.enum(['sandboxed-web', 'native-host']),
    service: z.boolean().default(false),
    i18n: translationDeclaration.optional(),
    icon: pathSchema.optional(),
    iconDark: pathSchema.optional(),
    permissions: z
      .array(z.string().regex(/^[a-z][a-z0-9_.-]{0,127}$/))
      .max(64)
      .default([]),
    consumes: z.array(seedConsumedCapabilitySchema).max(64).default([]),
    resources: z.array(resourceSchema).min(1).max(2_000),
    sidecars: z
      .array(
        z
          .object({ id: z.string().regex(/^[a-z][a-z0-9_.-]{0,127}$/), path: pathSchema, executable: z.literal(true) })
          .strict(),
      )
      .max(8)
      .default([]),
  })
  .strict()
  .superRefine((manifest, context) => {
    const permissions = new Set(manifest.permissions);
    if (permissions.size !== manifest.permissions.length)
      context.addIssue({ code: 'custom', path: ['permissions'], message: 'Duplicate permission.' });
    for (const permission of permissions)
      if (
        (permission === 'network' || permission.startsWith('network.')) &&
        !(seedNetworkPermissions as readonly string[]).includes(permission)
      ) {
        context.addIssue({ code: 'custom', path: ['permissions'], message: 'Unsupported network permission.' });
      }
    if (manifest.runtime === 'native-host' && !manifest.service) {
      context.addIssue({ code: 'custom', path: ['service'], message: 'Native runtimes require a service entry.' });
    }
    const paths = new Set<string>();
    for (const [index, resource] of manifest.resources.entries()) {
      const key = resource.path.normalize('NFC').toLowerCase();
      if (paths.has(key) || key === 'manifest.json')
        context.addIssue({
          code: 'custom',
          path: ['resources', index],
          message: 'Duplicate or self-referential resource.',
        });
      paths.add(key);
    }
    if (!paths.has('main.js'))
      context.addIssue({ code: 'custom', path: ['resources'], message: 'main.js is required.' });
    for (const asset of [manifest.icon, manifest.iconDark])
      if (asset && (!paths.has(asset.normalize('NFC').toLowerCase()) || !/\.(svg|png|webp|jpe?g)$/i.test(asset))) {
        context.addIssue({ code: 'custom', path: ['icon'], message: 'Icon must reference a declared image resource.' });
      }
    for (const sidecar of manifest.sidecars)
      if (
        !sidecar.path.startsWith('sidecars/') ||
        !paths.has(sidecar.path.normalize('NFC').toLowerCase()) ||
        !manifest.permissions.includes('process.sidecar')
      ) {
        context.addIssue({
          code: 'custom',
          path: ['sidecars'],
          message: 'Sidecar must declare its resource and process.sidecar permission.',
        });
      }
    if (new Set(manifest.sidecars.map((sidecar) => sidecar.id)).size !== manifest.sidecars.length)
      context.addIssue({ code: 'custom', path: ['sidecars'], message: 'Duplicate sidecar.' });
    for (const resource of Object.values(manifest.i18n?.resources ?? {})) {
      if (!paths.has(resource.normalize('NFC').toLowerCase()) || !resource.endsWith('.json'))
        context.addIssue({ code: 'custom', path: ['i18n'], message: 'Translations must be declared JSON resources.' });
    }
  });

export type SeedPluginJsonManifest = z.infer<typeof seedPluginJsonManifestSchema>;

export function normalizeJsonPluginManifest(
  document: SeedPluginJsonManifest,
  translations: PluginTranslations = { defaultLocale: 'en-US', resources: { 'en-US': {} } },
): SeedPluginManifest {
  createPluginI18n(translations);
  const name =
    typeof document.name === 'string'
      ? { en_US: document.name, zh_Hans: document.name }
      : (resolvePluginLocalizedMetadata(document.name, translations) as { en_US: string; zh_Hans: string });
  const description =
    typeof document.description === 'string'
      ? { en_US: document.description, zh_Hans: document.description }
      : (resolvePluginLocalizedMetadata(document.description, translations) as { en_US: string; zh_Hans: string });
  seedLocalizedTextSchema(100).parse(name);
  seedLocalizedTextSchema(500).parse(description);
  return {
    id: document.id,
    version: document.version,
    name,
    description,
    // Existing display contracts call this field publisher; v2 supplies author attribution, not account identity.
    publisher: document.author,
    minSeedVersion: document.minAppVersion,
    icon: document.icon ? './' + document.icon : '',
    iconDark: document.iconDark ? './' + document.iconDark : undefined,
    runtime: { kind: document.runtime },
    permissions: document.permissions,
    consumes: document.consumes as SeedPluginManifest['consumes'],
    sidecars: document.sidecars.map((sidecar) => ({ ...sidecar, path: './' + sidecar.path })),
    jsonManifest: document,
    translations,
  };
}

/** Resource reads only; even a disabled plugin's metadata is available without loading main.js. */
export async function readJsonPluginTranslations(
  document: SeedPluginJsonManifest,
  read: (path: string) => Promise<Buffer>,
): Promise<PluginTranslations> {
  if (!document.i18n) return { defaultLocale: 'en-US', resources: { 'en-US': {} } };
  const resources: PluginTranslations['resources'] = {};
  let bytes = 0;
  for (const [locale, path] of Object.entries(document.i18n.resources)) {
    const body = await read(path);
    bytes += body.length;
    if (bytes > 2 * 1024 * 1024) throw new Error('Plugin translation resources exceed size limit.');
    resources[locale] = JSON.parse(body.toString('utf8'));
  }
  const bundle = { defaultLocale: document.i18n.defaultLocale, resources };
  createPluginI18n(bundle);
  // Check references through the default resource, including before any plugin code can run.
  resolvePluginTranslationReferences([document.name, document.description], bundle, bundle.defaultLocale);
  return bundle;
}
